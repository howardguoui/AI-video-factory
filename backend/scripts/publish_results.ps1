# Run the quality benchmark on this GPU machine and publish the results to GitHub.
#   .\backend\scripts\publish_results.ps1                       # zh->en, 50 clips
#   .\backend\scripts\publish_results.ps1 -Src ja -Limit 100
#   .\backend\scripts\publish_results.ps1 -SkipRun              # just commit results already on disk
param(
    [string]$Src = "zh",
    [string]$Tgt = "en",
    [int]$Limit = 50,
    [switch]$SkipRun
)
$ErrorActionPreference = "Stop"
$repo = Resolve-Path "$PSScriptRoot\..\.."
Set-Location "$repo\backend"
$python = if (Test-Path ".\venv\Scripts\python.exe") { ".\venv\Scripts\python.exe" } else { "python" }

if (-not $SkipRun) {
    & $python -m pip install -q -r evals\requirements.txt
    & $python -m evals.quality_eval --src $Src --tgt $Tgt --limit $Limit
    if ($LASTEXITCODE -ne 0) { throw "quality_eval failed" }
}

Set-Location $repo
if (-not (git status --porcelain backend/evals/results)) { Write-Host "No new results to publish."; exit 0 }
$gpu = (nvidia-smi --query-gpu=name --format=csv,noheader 2>$null | Select-Object -First 1)
if (-not $gpu) { $gpu = "GPU" }
git add backend/evals/results
git commit -m "Quality benchmark results: $(Get-Date -Format yyyy-MM-dd), $Src->$Tgt on $gpu" -m "Generated by backend/scripts/publish_results.ps1 from real runs."
git pull --rebase origin AI-feature-implementation
git push origin AI-feature-implementation
Write-Host "Published. See backend/evals/results/latest.md on GitHub."
